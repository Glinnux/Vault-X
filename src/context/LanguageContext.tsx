interface LanguageContextType {
  selectedPreference: 'auto' | SupportedLanguage;
  detectedPhoneLanguage: SupportedLanguage;
  currentLanguage: SupportedLanguage;
  isAutoMode: boolean;
  isRTL: boolean;
  setLanguage: (lang: 'auto' | SupportedLanguage) => void;
  t: (key: string, fallback?: string) => string;
  currentLangInfo: LanguageInfo;
}

const STORAGE_KEY = 'clockin_vault_selected_lang';

function detectDevicePhoneLanguage(): SupportedLanguage {
  try {
    const rawLang =
      (navigator.languages && navigator.languages[0]) ||
      navigator.language ||
      'en';
    const primary = rawLang.toLowerCase().split(/[-_]/)[0];
    const match = SUPPORTED_LANGUAGES.find((l) => l.code === primary);
    return match ? match.code : 'en';
  } catch (_e) {
    return 'en';
  }
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [detectedPhoneLanguage, setDetectedPhoneLanguage] = useState<SupportedLanguage>(
    detectDevicePhoneLanguage
  );

  const [selectedPreference, setSelectedPreference] = useState<'auto' | SupportedLanguage>(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'auto' || SUPPORTED_LANGUAGES.some((l) => l.code === stored)) {
        return stored as 'auto' | SupportedLanguage;
      }
    } catch (_e) {
      // ignore
    }
    return 'auto'; // Default to configuring to the phone's language!
  });

  // Listen to phone/browser language changes dynamically
  useEffect(() => {
    const handleLanguageChange = () => {
      const detected = detectDevicePhoneLanguage();
      setDetectedPhoneLanguage(detected);
    };

    window.addEventListener('languagechange', handleLanguageChange);
    return () => window.removeEventListener('languagechange', handleLanguageChange);
  }, []);

  const isAutoMode = selectedPreference === 'auto';
  const currentLanguage: SupportedLanguage = isAutoMode
    ? detectedPhoneLanguage
    : selectedPreference;

  const currentLangInfo = useMemo(() => {
    return (
      SUPPORTED_LANGUAGES.find((l) => l.code === currentLanguage) ||
      SUPPORTED_LANGUAGES[0]
    );
  }, [currentLanguage]);

  const isRTL = currentLangInfo.dir === 'rtl';

  // Keep HTML document dir and lang synchronized
  useEffect(() => {
    try {
      document.documentElement.lang = currentLanguage;
      document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    } catch (_e) {
      // ignore
    }
  }, [currentLanguage, isRTL]);

  const setLanguage = (lang: 'auto' | SupportedLanguage) => {
    setSelectedPreference(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (_e) {
      // ignore
    }
  };

  const t = (key: string, fallback?: string): string => {
    const currentDict = TRANSLATIONS[currentLanguage];
    if (currentDict && currentDict[key]) {
      return currentDict[key];
    }
    const defaultDict = TRANSLATIONS['en'];
    if (defaultDict && defaultDict[key]) {
      return defaultDict[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        selectedPreference,
        detectedPhoneLanguage,
        currentLanguage,
        isAutoMode,
        isRTL,
        setLanguage,
        t,
        currentLangInfo,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
